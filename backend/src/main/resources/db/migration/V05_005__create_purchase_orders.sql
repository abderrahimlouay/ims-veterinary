-- Purchase orders (database.md §3.3, FR-PURCH-003/004, BR-PURCH-001…003): numbered at creation (ADR-097),
-- totals computed by the service per line (ADR-093) and stored; draft → validated → sent → partially_received →
-- closed, cancelled from draft/validated/sent with a reason, forced close of a partially received order with a
-- reason (ADR-096, ADR-105, SD-130). version for optimistic locking (ADR-027).
CREATE TABLE purchase_orders (
    id            BIGINT        NOT NULL AUTO_INCREMENT,
    number        VARCHAR(30)   NOT NULL,
    supplier_id   BIGINT        NOT NULL,
    status        VARCHAR(30)   NOT NULL DEFAULT 'draft',
    order_date    DATE          NOT NULL,
    expected_date DATE          NULL,
    total_ht      DECIMAL(14,2) NOT NULL DEFAULT 0,
    total_vat     DECIMAL(14,2) NOT NULL DEFAULT 0,
    total_ttc     DECIMAL(14,2) NOT NULL DEFAULT 0,
    created_by    BIGINT        NOT NULL,
    created_at    DATETIME(6)   NOT NULL,
    updated_at    DATETIME(6)   NOT NULL,
    validated_by  BIGINT        NULL,
    validated_at  DATETIME(6)   NULL,
    sent_by       BIGINT        NULL,
    sent_at       DATETIME(6)   NULL,
    cancel_reason TEXT          NULL,
    cancelled_by  BIGINT        NULL,
    cancelled_at  DATETIME(6)   NULL,
    closed_reason TEXT          NULL,
    closed_by     BIGINT        NULL,
    closed_at     DATETIME(6)   NULL,
    version       BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT pk_purchase_orders PRIMARY KEY (id),
    CONSTRAINT uq_purchase_orders_number UNIQUE (number),
    CONSTRAINT fk_purchase_orders_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id),
    CONSTRAINT fk_purchase_orders_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT fk_purchase_orders_validated_by FOREIGN KEY (validated_by) REFERENCES users (id),
    CONSTRAINT fk_purchase_orders_sent_by FOREIGN KEY (sent_by) REFERENCES users (id),
    CONSTRAINT fk_purchase_orders_cancelled_by FOREIGN KEY (cancelled_by) REFERENCES users (id),
    CONSTRAINT fk_purchase_orders_closed_by FOREIGN KEY (closed_by) REFERENCES users (id),
    CONSTRAINT ck_purchase_orders_status CHECK (status IN ('draft', 'validated', 'sent', 'partially_received',
        'closed', 'cancelled')),
    CONSTRAINT ck_purchase_orders_totals CHECK (total_ht >= 0 AND total_vat >= 0 AND total_ttc >= 0),
    CONSTRAINT ck_purchase_orders_cancelled CHECK ((status = 'cancelled') = (cancelled_at IS NOT NULL)
        AND (cancelled_at IS NULL) = (cancel_reason IS NULL)),
    CONSTRAINT ck_purchase_orders_closed_reason CHECK (closed_reason IS NULL OR status = 'closed'),
    INDEX idx_purchase_orders_status (status, order_date),
    INDEX idx_purchase_orders_supplier (supplier_id, order_date)
);
