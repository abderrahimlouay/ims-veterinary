package com.imsvet.ims.purchasing.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import java.math.BigDecimal;

/**
 * One product of a purchase order (BR-PURCH-002): quantity in the ordered unit and in base units, price per ordered
 * unit with 4 decimals (ADR-094), discount, VAT rate, amounts per line (ADR-093; also generated by the database,
 * not mapped here), received base quantity (slice 5).
 */
@Entity
@Table(name = "purchase_order_lines")
public class PurchaseOrderLine {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "purchase_order_id", nullable = false, updatable = false)
    private PurchaseOrder order;

    @Column(name = "product_id", nullable = false, updatable = false)
    private Long productId;

    @Column(name = "unit_id", updatable = false)
    private Long unitId;

    @Column(nullable = false, precision = 14, scale = 3, updatable = false)
    private BigDecimal quantity;

    @Column(name = "quantity_base", nullable = false, precision = 14, scale = 3, updatable = false)
    private BigDecimal quantityBase;

    @Column(name = "received_base", nullable = false, precision = 14, scale = 3)
    private BigDecimal receivedBase;

    @Column(name = "unit_price", nullable = false, precision = 14, scale = 4, updatable = false)
    private BigDecimal unitPrice;

    @Column(name = "discount_pct", nullable = false, precision = 5, scale = 2, updatable = false)
    private BigDecimal discountPct;

    @Column(name = "vat_rate", nullable = false, precision = 5, scale = 2, updatable = false)
    private BigDecimal vatRate;

    protected PurchaseOrderLine() {
    }

    PurchaseOrderLine(PurchaseOrder order, Long productId, Long unitId, BigDecimal quantity, BigDecimal quantityBase,
            BigDecimal unitPrice, BigDecimal discountPct, BigDecimal vatRate) {
        this.order = order;
        this.productId = productId;
        this.unitId = unitId;
        this.quantity = quantity;
        this.quantityBase = quantityBase;
        this.receivedBase = BigDecimal.ZERO.setScale(3);
        this.unitPrice = unitPrice;
        this.discountPct = discountPct;
        this.vatRate = vatRate;
    }

    public BigDecimal lineHt() {
        return OrderAmounts.lineHt(quantity, unitPrice, discountPct);
    }

    public BigDecimal lineVat() {
        return OrderAmounts.lineVat(lineHt(), vatRate);
    }

    public BigDecimal outstandingBase() {
        return quantityBase.subtract(receivedBase);
    }

    public Long id() {
        return id;
    }

    public Long productId() {
        return productId;
    }

    public Long unitId() {
        return unitId;
    }

    public BigDecimal quantity() {
        return quantity;
    }

    public BigDecimal quantityBase() {
        return quantityBase;
    }

    public BigDecimal receivedBase() {
        return receivedBase;
    }

    public BigDecimal unitPrice() {
        return unitPrice;
    }

    public BigDecimal discountPct() {
        return discountPct;
    }

    public BigDecimal vatRate() {
        return vatRate;
    }
}
