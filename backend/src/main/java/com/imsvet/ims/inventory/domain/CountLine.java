package com.imsvet.ims.inventory.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;

/**
 * One line of a count (database.md §3.4): an existing lot, or a lot found during the count and unknown to the system
 * (no lot yet: product, lot number, expiry and unit cost, ADR-074). Saving a counted quantity stores the lot balance
 * and last movement id at that moment, the watermark (ADR-072, BR-INV-008); the variance is taken against them
 * ({@code variance_qty} is also generated by the database). A regularised line never changes (BR-INV-004).
 */
@Entity
@Table(name = "inventory_lines")
public class CountLine {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "inventory_id", nullable = false, updatable = false)
    private Long countId;

    @Column(name = "product_id", nullable = false, updatable = false)
    private Long productId;

    @Column(name = "lot_id")
    private Long lotId;

    @Column(name = "found_lot_number", length = 60, updatable = false)
    private String foundLotNumber;

    @Column(name = "found_expiry_date", updatable = false)
    private LocalDate foundExpiryDate;

    @Column(name = "found_unit_cost", precision = 14, scale = 4, updatable = false)
    private BigDecimal foundUnitCost;

    @Column(name = "theoretical_qty", nullable = false, precision = 14, scale = 3, updatable = false)
    private BigDecimal theoreticalQty;

    @Column(name = "counted_qty", precision = 14, scale = 3)
    private BigDecimal countedQty;

    @Column(name = "counted_at")
    private Instant countedAt;

    @Column(name = "counted_by")
    private Long countedBy;

    @Column(name = "balance_at_count", precision = 14, scale = 3)
    private BigDecimal balanceAtCount;

    @Column(name = "watermark_movement_id")
    private Long watermarkMovementId;

    @Column(nullable = false)
    private boolean regularized;

    @Column(name = "adjustment_movement_id")
    private Long adjustmentMovementId;

    protected CountLine() {
    }

    private CountLine(Long countId, Long productId, Long lotId, BigDecimal theoreticalQty) {
        this.countId = countId;
        this.productId = productId;
        this.lotId = lotId;
        this.theoreticalQty = theoreticalQty;
    }

    /** {@code theoreticalQty}: the lot balance when the line is created (informational, ADR-072). */
    public static CountLine ofLot(Long countId, Long productId, Long lotId, BigDecimal theoreticalQty) {
        return new CountLine(countId, productId, lotId, theoreticalQty);
    }

    public static CountLine ofFoundLot(Long countId, Long productId, String lotNumber, LocalDate expiryDate,
            BigDecimal unitCost) {
        CountLine line = new CountLine(countId, productId, null, BigDecimal.ZERO);
        line.foundLotNumber = lotNumber;
        line.foundExpiryDate = expiryDate;
        line.foundUnitCost = unitCost;
        return line;
    }

    /** Takes a new watermark (ADR-072): a found lot has balance 0 and no movement. */
    public void count(BigDecimal quantity, BigDecimal balance, Long watermark, Long userId, Instant now) {
        if (regularized) {
            throw new IllegalStateException("Line " + id + " is regularised");
        }
        this.countedQty = quantity;
        this.balanceAtCount = balance;
        this.watermarkMovementId = watermark;
        this.countedBy = userId;
        this.countedAt = now;
    }

    /** A found lot gets its lot when regularisation creates it (ADR-074). */
    public void attachLot(Long createdLotId) {
        if (lotId != null) {
            throw new IllegalStateException("Line " + id + " already has lot " + lotId);
        }
        this.lotId = createdLotId;
    }

    /** At most once (BR-INV-004); {@code movementId} null for a zero variance. */
    public void regularize(Long movementId) {
        if (regularized) {
            throw new IllegalStateException("Line " + id + " is regularised");
        }
        this.regularized = true;
        this.adjustmentMovementId = movementId;
    }

    /** {@code counted − balance at count} (BR-INV-001), or null while not counted. */
    public BigDecimal varianceQty() {
        return countedQty == null ? null : countedQty.subtract(balanceAtCount);
    }

    public Long id() {
        return id;
    }

    public Long countId() {
        return countId;
    }

    public Long productId() {
        return productId;
    }

    public Long lotId() {
        return lotId;
    }

    public String foundLotNumber() {
        return foundLotNumber;
    }

    public LocalDate foundExpiryDate() {
        return foundExpiryDate;
    }

    public BigDecimal foundUnitCost() {
        return foundUnitCost;
    }

    public BigDecimal theoreticalQty() {
        return theoreticalQty;
    }

    public BigDecimal countedQty() {
        return countedQty;
    }

    public Instant countedAt() {
        return countedAt;
    }

    public Long countedBy() {
        return countedBy;
    }

    public BigDecimal balanceAtCount() {
        return balanceAtCount;
    }

    public Long watermarkMovementId() {
        return watermarkMovementId;
    }

    public boolean regularized() {
        return regularized;
    }

    public Long adjustmentMovementId() {
        return adjustmentMovementId;
    }
}
